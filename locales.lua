-- Full set of UI strings, to be sent to the NUI
function LUI()
    local locale = Locales[Config.Locale] or Locales.en
    local out = {}
    for k, v in pairs(Locales.en.ui) do out[k] = v end
    if locale.ui then
        for k, v in pairs(locale.ui) do out[k] = v end
    end
    return out
end

function L(key, ...)
    local str = (Locales[Config.Locale] or Locales.en)[key] or Locales.en[key] or key
    if select('#', ...) > 0 then
        return str:format(...)
    end
    return str
end
